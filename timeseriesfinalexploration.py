threshold = cyber["Residuals"].mean() + 3 * cyber["Residuals"].std()
cyber["Anomaly"] = cyber["Residuals"] > threshold

# Plot the time series with forecast and anomalies
plt.figure(figsize=(14,6))
plt.plot(cyber.index, cyber["Network Attack"], label="Actual", color='blue', alpha=0.6)
plt.plot(cyber.index, cyber["Forecast"], label="Forecast", color='red', linestyle="dashed")
plt.scatter(cyber.index[cyber["Anomaly"]], cyber["Network Attack"][cyber["Anomaly"]],
            color='black', marker='o', label="Anomalies")
plt.xlabel("Date")
plt.ylabel("Network Attack Count")
plt.title("Cyber Attack Time Series with Forecast & Anomalies")
plt.legend()
plt.grid()
plt.show()

